pub fn source_for(locale: &str) -> Option<&'static str> {
    match locale {
        "es" => Some(ES),
        "en" => Some(EN),
        "pt" => Some(PT),
        "ar" => Some(AR),
        "fr" => Some(FR),
        _ => None,
    }
}

